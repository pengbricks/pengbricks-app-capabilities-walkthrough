        {"order_id": 3, "customer_id": "B", "customer_name": "b", "region": "E", "order_ts": t(2024, 3, 2, 8), "amount": Decimal("99.00"), "status": "CANCELLED", "load_ts": t(2024, 3, 2, 9)},
