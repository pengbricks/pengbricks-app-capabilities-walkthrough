def test_split_steps_finds_all(steps):
    assert [s.step_id for s in steps] == list(range(1, 14))
    assert steps[5].name == "stage_orders"
    assert not steps[0].sql.startswith("--")


@pytest.mark.parametrize("sql,construct", [
    ("BEGIN TRY SELECT 1 END TRY BEGIN CATCH THROW; END CATCH", "try_catch"),
    ("DECLARE c CURSOR FOR SELECT 1; OPEN c;", "cursor"),
    ("DECLARE @d DATE = GETDATE(); WHILE @d < 5 BEGIN SET @d = 1 END", "while_loop"),
    ("WITH r AS (SELECT 1 a) DELETE FROM r WHERE a > 1", "cte_dml"),
    ("MERGE dbo.t AS a USING s ON a.k = s.k WHEN MATCHED THEN UPDATE SET a.v = s.v", "merge"),
    ("SELECT a INTO #t FROM dbo.x", "temp_table"),
    ("CREATE TABLE dbo.t (k INT IDENTITY(1,1))", "ddl_identity"),
    ("CREATE TABLE dbo.t (k INT)", "ddl"),
    ("INSERT INTO dbo.t SELECT a, COUNT(*) FROM x GROUP BY a", "aggregate_insert"),
    ("SELECT 1", "select"),
])
def test_classify_primary(sql, construct):
    assert h.classify(sql)[0] == construct


def test_classify_tags():
    _, tags = h.classify("SELECT TOP (5) ISNULL(a, 0), GETDATE() INTO #t FROM x")
    assert {"top", "isnull", "getdate", "temp_table"} <= set(tags)


def test_convert_clean():
    c = h.convert_statement("INSERT INTO dbo.f SELECT CAST(o AS DATE), COUNT(*) FROM #s GROUP BY CAST(o AS DATE)", "cat", "sch")
    assert c.status == "clean" or c.status == "warning"
    assert "`cat`.`sch`.`f`" in c.converted_sql or "`cat`.`sch`.f" in c.converted_sql


def test_convert_plain_clean():
    c = h.convert_statement("INSERT INTO dbo.etl_log (a) SELECT ISNULL(b, 0) FROM dbo.x", "cat", "sch")
    assert c.status == "clean"
    assert "COALESCE" in c.converted_sql


def test_convert_temp_table_warns_and_replaces():
    c = h.convert_statement("SELECT TOP (10) ISNULL(a,'x') AS a, GETDATE() AS t INTO #stg FROM dbo.raw ORDER BY a", "cat", "sch")
    assert c.status == "warning"
    assert c.converted_sql.startswith("CREATE OR REPLACE TABLE")
    assert "tmp_stg" in c.converted_sql and "LIMIT 10" in c.converted_sql
    assert "#" not in c.converted_sql


def test_convert_identity_warns():
    c = h.convert_statement("CREATE TABLE dbo.d (k INT IDENTITY(1,1) NOT NULL, n NVARCHAR(10))", "cat", "sch")
    assert c.status == "warning"
    assert "GENERATED BY DEFAULT AS IDENTITY" in c.converted_sql


def test_convert_merge_warns():
    c = h.convert_statement("MERGE dbo.d AS t USING (SELECT 1 a) AS s ON t.a = s.a WHEN NOT MATCHED BY TARGET THEN INSERT (a) VALUES (s.a)", "cat", "sch")
    assert c.status == "warning"
    assert c.converted_sql.startswith("MERGE INTO")


@pytest.mark.parametrize("sql", [
    "DECLARE c CURSOR FOR SELECT 1",
    "WHILE 1 = 1 BEGIN SELECT 1 END",
    "BEGIN TRY SELECT 1 END TRY BEGIN CATCH THROW END CATCH",
    "WITH r AS (SELECT 1 a) DELETE FROM r WHERE a > 1",
])
def test_convert_manual(sql):
    c = h.convert_statement(sql, "cat", "sch")
    assert c.status == "manual" and c.notes and not c.converted_sql


def test_whole_workload_status_counts(spec, steps):
    statuses = [h.convert_statement(s.sql, "c", "s").status for s in steps]
    assert statuses.count("manual") == 4
    summary, _ = h.summarize(statuses)
    assert summary["remediation_count"] == 4
    assert summary["automated_coverage_pct"] == round(100 * 9 / 13, 1)


def test_remediation_blocks_cover_manual_steps(spec, steps):
    with open(os.path.join(ROOT, spec["workload"]["remediation_sql"])) as f:
        rem = {s.step_id for s in h.split_steps(f.read())}
    manual = {s.step_id for s in steps if h.convert_statement(s.sql, "c", "s").status == "manual"}
    assert manual == rem


