"""Generic helpers: split a legacy script into steps, classify each step by
construct, convert T-SQL to Databricks SQL with sqlglot, and compute effort.
Nothing here is specific to one use case; the use case spec supplies the details."""
import logging
import re
from dataclasses import dataclass, field

import sqlglot
from sqlglot import exp

STEP_RE = re.compile(r"^--\s*STEP\s+(\d+)\s*\|\s*(\w+)\s*$", re.MULTILINE)

# Primary construct = first match in this order. Pattern runs on SQL with comments removed.
CONSTRUCT_RULES = [
    ("try_catch", r"\bBEGIN\s+TRY\b"),
    ("cursor", r"\bDECLARE\s+\w+\s+CURSOR\b"),
    ("while_loop", r"\bWHILE\b"),
    ("cte_dml", r"^\s*WITH\b.*\b(DELETE|UPDATE)\s+(FROM\s+)?\w+"),
    ("merge", r"^\s*MERGE\b"),
    ("temp_table", r"#\w+\s*$|\bINTO\s+#\w+"),
    ("ddl_identity", r"^\s*CREATE\s+TABLE\b.*\bIDENTITY\s*\("),
    ("ddl", r"^\s*CREATE\s+TABLE\b"),
    ("aggregate_insert", r"^\s*INSERT\b.*\bGROUP\s+BY\b"),
    ("insert", r"^\s*INSERT\b"),
    ("select", r"^\s*SELECT\b"),
]
# Extra tags recorded on every step, even when they are not the primary construct.
FEATURE_TAGS = {
    "temp_table": r"#\w+",
    "identity": r"\bIDENTITY\s*\(",
    "merge": r"\bMERGE\b",
    "top": r"\bTOP\s*\(?\s*\d+",
    "isnull": r"\bISNULL\s*\(",
    "getdate": r"\bGETDATE\s*\(",
    "window_function": r"\bOVER\s*\(",
    "cursor": r"\bCURSOR\b",
    "while_loop": r"\bWHILE\b",
    "try_catch": r"\bBEGIN\s+TRY\b",
    "variables": r"@\w+",
}
MANUAL_REASONS = {
    "try_catch": "TRY/CATCH has no Databricks SQL equivalent. Use job task failure handling (retries, notifications) and log the outcome from the job.",
    "cursor": "Row-by-row cursor. Rewrite as a set-based statement.",
    "while_loop": "Procedural WHILE loop. Rewrite as a set-based statement (for example sequence() or explode()).",
    "cte_dml": "DML against a CTE is not supported on Delta tables. Rewrite as DELETE/MERGE with a predicate.",
}
WARNING_REASONS = {
    "temp_table": "Temp table becomes a Delta table with the temp prefix, dropped at the end of the run. Temp views would be lazy.",
    "identity": "IDENTITY becomes BIGINT GENERATED BY DEFAULT AS IDENTITY. Generated values are unique but not guaranteed contiguous.",
    "top": "TOP becomes LIMIT. Confirm the ORDER BY decides which rows are kept.",
    "merge": "MERGE converted. Databricks MERGE fails if several source rows match one target row, so confirm the source is unique per key.",
}
TAG_ORDER_FOR_WARNING = ["temp_table", "identity", "top", "merge"]


@dataclass
class Step:
    step_id: int
    name: str
    sql: str


@dataclass
class Conversion:
    status: str  # clean | warning | manual
    notes: list = field(default_factory=list)
    converted_sql: str = ""


def strip_comments(sql):
    lines = [re.sub(r"--.*$", "", ln) for ln in sql.splitlines()]
    return "\n".join(ln for ln in lines if ln.strip()).strip()


def split_steps(text):
    """Split a script on '-- STEP nn | name' markers. Comments are removed from step SQL."""
    marks = list(STEP_RE.finditer(text))
    steps = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        steps.append(Step(int(m.group(1)), m.group(2), strip_comments(text[m.end():end]).rstrip(";").strip()))
    return steps


def split_statements(sql):
    return [s.strip() for s in sql.split(";") if s.strip()]


def classify(sql):
    """Return (primary_construct, [tags])."""
    body = strip_comments(sql)
    flat = re.sub(r"\s+", " ", body)
    primary = "other"
    for name, pat in CONSTRUCT_RULES:
        if re.search(pat, flat, re.IGNORECASE | re.DOTALL):
            primary = name
            break
    tags = [t for t, pat in FEATURE_TAGS.items() if re.search(pat, flat, re.IGNORECASE)]
    return primary, tags


class _Capture(logging.Handler):
    def __init__(self):
        super().__init__()
        self.messages = []

    def emit(self, record):
        self.messages.append(record.getMessage())


def _qualify(tree, catalog, schema, legacy_schema, temp_prefix):
    for t in tree.find_all(exp.Table):
        legacy = (t.args.get("db") is not None and t.args["db"].name.lower() == legacy_schema.lower())
        temp = t.args.get("db") is None and t.name.startswith(temp_prefix)
        if legacy or temp:
            t.set("db", exp.to_identifier(schema, quoted=True))
            t.set("catalog", exp.to_identifier(catalog, quoted=True))


def convert_statement(sql, catalog, schema, legacy_schema="dbo", temp_prefix="tmp_"):
    """Convert one legacy step to Databricks SQL. Never raises; returns a Conversion."""
    primary, tags = classify(sql)
    if primary in MANUAL_REASONS:
        return Conversion("manual", [MANUAL_REASONS[primary]])
    text = re.sub(r"#(\w+)", lambda m: temp_prefix + m.group(1), strip_comments(sql))
    capture = _Capture()
    log = logging.getLogger("sqlglot")
    log.addHandler(capture)
    try:
        trees = sqlglot.parse(text, read="tsql")
        if not trees or any(t is None or isinstance(t, exp.Command) for t in trees):
            return Conversion("manual", ["sqlglot could not parse the statement and fell back to a raw command."])
        out = []
        for tree in trees:
            _qualify(tree, catalog, schema, legacy_schema, temp_prefix)
            out.append(tree.sql(dialect="databricks"))
    except Exception as e:  # parse or generate failure
        return Conversion("manual", [f"sqlglot error: {str(e).splitlines()[0][:200]}"])
    finally:
        log.removeHandler(capture)
    converted = ";\n".join(out)
    converted = re.sub(r"^CREATE TABLE (\S+) AS", r"CREATE OR REPLACE TABLE \1 AS", converted)
    notes = [WARNING_REASONS[t] for t in TAG_ORDER_FOR_WARNING if t in tags]
    notes += [f"sqlglot: {m[:200]}" for m in capture.messages]
    return Conversion("warning" if notes else "clean", notes or ["Converted without changes needing review."], converted)


def effort_model(counts, effort_spec):
    """counts: {'clean': n, 'warning': n, 'manual': n}. Returns one row per role."""
    rows = []
    for role, cfg in effort_spec["roles"].items():
        per = cfg["per_status"]
        parts = {s: round(counts.get(s, 0) * per[s], 2) for s in ("clean", "warning", "manual")}
        total = round(cfg["fixed"] + sum(parts.values()), 2)
        rows.append({
            "role": role,
            "clean_hours": parts["clean"], "warning_hours": parts["warning"],
            "manual_hours": parts["manual"], "fixed_hours": float(cfg["fixed"]),
            "total_hours": total, "assumption": cfg["assumption"],
        })
    return rows


def summarize(statuses):
    total = len(statuses)
    counts = {s: statuses.count(s) for s in ("clean", "warning", "manual")}
    automated = counts["clean"] + counts["warning"]
    return {
        "total_statements": total, **{f"{k}_count": v for k, v in counts.items()},
        "automated_coverage_pct": round(100.0 * automated / total, 1) if total else 0.0,
        "remediation_count": counts["manual"],
    }, counts
