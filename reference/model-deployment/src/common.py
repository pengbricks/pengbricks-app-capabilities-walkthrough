"""Shared helpers for the model release job: spec loading, data generation, release gates."""

from __future__ import annotations

import re
from typing import Any

import yaml

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def load_spec(path: str) -> dict[str, Any]:
    with open(path) as handle:
        spec = yaml.safe_load(handle)
    validate_spec(spec)
    return spec


def validate_spec(spec: dict[str, Any]) -> None:
    names = [c["name"] for c in spec["data"]["columns"]]
    for name in [spec["model"]["name"], spec["data"]["table"], spec["label"]["name"], *names]:
        if not _IDENT.match(name):
            raise ValueError(f"Not a valid identifier: {name}")
    missing = [f for f in spec["features"] if f not in names]
    if missing:
        raise ValueError(f"Features not generated by the spec: {missing}")
    if spec["label"]["name"] in names:
        raise ValueError("Label name collides with a generated column")


def full_model_name(catalog: str, schema: str, spec: dict[str, Any]) -> str:
    return f"{catalog}.{schema}.{spec['model']['name']}"


def training_table(catalog: str, schema: str, spec: dict[str, Any]) -> str:
    return f"{catalog}.{schema}.{spec['data']['table']}"


def build_training_frame(spark, spec: dict[str, Any]):
    """Generate the training data with the sample-data generator. The same spec and seed give the same rows."""
    from pyspark.sql import functions as F

    import sample_data

    data = spec["data"]
    columns = [{"name": c["name"], "type": c["type"], "min": c["min"], "max": c["max"]} for c in data["columns"]]
    df = sample_data.generate(spark, columns, data["rows"], spec["seed"], "training", partitions=4, keep_id=True)
    for col in data["columns"]:
        df = df.withColumn(col["name"], F.col(col["name"]).cast("double"))
    return df.withColumn(spec["label"]["name"], F.expr(spec["label"]["expr"]))


def split_frame(pdf, spec: dict[str, Any]):
    """Deterministic train/holdout split on id, shared by training and the tests."""
    is_holdout = pdf["id"] % spec["data"]["holdout_mod"] == 0
    return pdf[~is_holdout], pdf[is_holdout]


def evaluate_gates(
    candidate_auc: float,
    min_auc: float,
    champion_auc: float | None,
    max_regression: float,
) -> list[tuple[str, bool, str]]:
    """Quality threshold and champion comparison. Returns (name, passed, detail) rows."""
    gates = [
        ("quality_threshold", candidate_auc >= min_auc, f"auc={candidate_auc:.4f} min={min_auc:.4f}")
    ]
    if champion_auc is None:
        gates.append(("champion_comparison", True, "no current champion"))
    else:
        floor = champion_auc - max_regression
        gates.append(
            (
                "champion_comparison",
                candidate_auc >= floor,
                f"candidate={candidate_auc:.4f} champion={champion_auc:.4f} allowed_regression={max_regression:.4f}",
            )
        )
    return gates


def run_url(host: str, experiment_id: str, run_id: str) -> str:
    return f"{host.rstrip('/')}/ml/experiments/{experiment_id}/runs/{run_id}"


def to_bool(value: Any) -> bool:
    return str(value).strip().lower() in {"true", "1", "yes"}
